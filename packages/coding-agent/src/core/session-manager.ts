export interface PendingEntry {
	type: "message";
	id: string;
	parentId: string | null;
	timestamp: string;
	offset: number;
	length: number;
	readonly __pending: true;
}

/**
 * compaction 前 message 条目的内存占位。仅元数据 + 磁盘偏移；
 * 访问 .message 前必须 materialize。字段顺序依赖 type/id/parentId/timestamp
 * 在序列化时位于 message 之前（peekEntryFields regex 依赖）。
 * 注意：该类型不加入 SessionEntry union，运行时以 FileEntry 形态存在于
 * fileEntries 中，下游通过 `__lazy` 标记 + optional chaining 防御。
 */
export interface LazyEntry {
	type: "message";
	id: string;
	parentId: string | null;
	timestamp: string;
	readonly __lazy: true;
	offset: number;
	length: number;
}

/**
 * 类型守卫：检测 LazyEntry 占位（compaction 前 message 的内存占位）。
 * 全仓统一经此判定，替代 `(e as { __lazy?: boolean }).__lazy` duck-typing；
 * 守卫通过后类型收窄为 LazyEntry，可直接访问 id/offset/length。
 */
export function isLazyEntry(e: unknown): e is LazyEntry {
	return (e as { __lazy?: boolean })?.__lazy === true;
}

